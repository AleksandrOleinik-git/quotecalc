<?php

namespace Database\Seeders;

use App\Models\User;
use Illuminate\Database\Seeder;
use Illuminate\Support\Str;

/**
 * Creates the admin with a fresh random password on every run.
 * The password is written only to the git-ignored .admin-credentials.local file, never to output.
 */
class AdminUserSeeder extends Seeder
{
    public const EMAIL = 'admin@quotecalc.test';

    public const CREDENTIALS_FILE = '.admin-credentials.local';

    public function run(): void
    {
        $password = Str::password(24, symbols: false);

        $admin = User::query()->firstOrNew(['email' => self::EMAIL]);
        $admin->name = 'Admin';
        $admin->password = $password;
        $admin->is_admin = true;
        $admin->email_verified_at = now();
        $admin->save();

        if (app()->runningUnitTests()) {
            return;
        }

        $path = base_path(self::CREDENTIALS_FILE);
        file_put_contents($path, implode(PHP_EOL, [
            '# Local admin login for /admin. Regenerated by `php artisan db:seed`. Do not commit.',
            'email='.self::EMAIL,
            'password='.$password,
            '',
        ]));
        chmod($path, 0600);

        $this->command->info('Admin credentials written to '.self::CREDENTIALS_FILE);
    }
}
